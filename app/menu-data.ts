export function dietaryText(tags?: string[]) {
  const labels: Record<string, string> = {
    GF: "Gluten free",
    V: "Vegetarian",
    VG: "Vegan",
  };
  return (
    tags
      ?.filter((tag) => tag !== "V" || !tags.includes("VG"))
      .map((tag) => labels[tag] ?? tag)
      .join(" · ") ?? ""
  );
}

